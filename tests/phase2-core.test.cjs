const assert=require('node:assert/strict');
const C=require('../assets/phase2-core.js');
const last=s=>C.tracePython(s).at(-1);
assert.equal(C.evaluate('2+3*4',{}),14);
assert.equal(C.evaluate('11//3',{}),3);
assert.deepEqual(C.evaluate('[1,2,3]',{}),[1,2,3]);
assert.deepEqual(last('total = 0\nfor n in [2, 4, 6]:\n    total += n\nprint(total)').vars,{total:12,n:6});
assert.deepEqual(last('x = [2, 4]\nx.append(6)\nprint(len(x))').output,['3']);
assert.deepEqual(last('n = 7\nif n > 5:\n    result = "large"\nprint(result)').output,['large']);
assert.deepEqual(last('n = 3\nif n > 5:\n    result = 1\nprint(n)').output,['3']);
assert.throws(()=>C.tracePython('import os'),/Unsupported statement|Unexpected indentation/);
assert.throws(()=>C.tracePython('x = __import__("os")'),/Only len/);
assert.throws(()=>C.tracePython('for i in range(100):\n    print(i)'),/range of at most/);
assert.throws(()=>C.tracePython('x = 1/0'),/Division by zero/);
assert.throws(()=>C.tracePython('x=0\nwhile True:\n    x+=1'),/Unsupported statement|Unexpected indentation/);
assert.throws(()=>C.tracePython('a = [1]\nprint(a[4])'),/List index out of range/);
const linear=C.initialize({task:'xor',width:0,rate:0.7});
const baseline=C.metrics(linear).loss;
C.train(linear,500);
assert.ok(Math.abs(C.metrics(linear).loss-Math.log(2))<0.003);
const hidden=C.initialize({task:'xor',width:4,rate:0.7});
const start=C.metrics(hidden);
const end=C.train(hidden,1000);
assert.ok(end.loss<0.04 && end.accuracy===1,{start,end});
assert.equal(C.train(C.initialize({task:'or',width:0,rate:0.7}),1000).accuracy,1);
const replay=C.initialize({task:'xor',width:4,rate:0.7});C.train(replay,1000);
assert.deepEqual(C.metrics(replay),C.metrics(hidden),'fixed seed reproducible');
assert.equal(C.checkER({bridge:'Enrollment',key:'composite',studentLink:'one-to-many',courseLink:'one-to-many'}).correct,true);
assert.equal(C.checkER({bridge:'Student',key:'student-only',studentLink:'one-to-many',courseLink:'many-to-many'}).score,1);
assert.equal(C.joinPreview('inner').length,3);
assert.deepEqual(C.joinPreview('left').at(-1),['Leila',null]);
assert.ok(C.ddl.includes('PRIMARY KEY (student_id, course_id)'));
console.log('PASS Phase 2 core: bounded Python tracer, toy SGD neural network, ER validation and join preview');
