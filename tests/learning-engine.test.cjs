const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const memory = new Map();
let clock = Date.UTC(2026, 9, 22);
class FakeDate extends Date { constructor(...args) { super(...(args.length ? args : [clock])); } static now() { return clock; } }
const context = { window: {}, localStorage: { getItem: x => memory.get(x) ?? null, setItem: (k, v) => memory.set(k, v) }, Date: FakeDate };
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../assets/learning-engine.js'), 'utf8'), context);
const E = context.window.LearningEngine;
const c = { id: 'python', lessons: [{id: 'hello-variables'}, {id: 'lists-loops'}] };
assert.equal(E.info('python','hello-variables').code, 'unseen');
assert.equal(E.recordDiagnostic('python',[{lessonId:'hello-variables',correct:false}]),true);
assert.equal(E.recordDiagnostic('python',[{lessonId:'hello-variables',correct:true}]),false);
assert.equal(E.info('python','hello-variables').code, 'diagnostic');
E.recordAttempt('python','hello-variables','quiz',0,false);
E.recordAttempt('python','hello-variables','quiz',0,true);
assert.equal(E.info('python','hello-variables').passed,1);
const before = E.info('python','hello-variables').nextReviewAt;
assert.equal(before,clock + 86400000);
E.recordAttempt('python','hello-variables','quiz',0,true);
assert.equal(E.info('python','hello-variables').nextReviewAt,before);
assert.equal(E.review('python','hello-variables',true),false);
clock += 86400000;
assert.equal(E.due([c]).length,1);
assert.equal(E.review('python','hello-variables',true),true);
assert.equal(E.info('python','hello-variables').nextReviewAt,clock+3*86400000);
clock += 3*86400000;
E.review('python','hello-variables',true);
assert.equal(E.info('python','hello-variables').code,'retained');
assert.equal(E.info('python','hello-variables').nextReviewAt,clock+7*86400000);
E.hint('python','hello-variables','lab:0',1); E.hint('python','hello-variables','lab:0',3);
assert.equal(E.exportData().skills['python/hello-variables'].hinted['lab:0'],3);
E.recordAttempt('python','lists-loops','challenge','list-count',true);
assert.equal(E.summary(c).started,2);
assert.equal(E.due([c],true).length,2);
console.log('PASS learning engine: placement, attempts, idempotency, review scheduling, persistence, hints');
